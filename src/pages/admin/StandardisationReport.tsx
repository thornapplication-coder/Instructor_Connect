import { Printer, Table2 } from 'lucide-react'
import { useMemo } from 'react'
import { useTranslation } from 'react-i18next'
import { csvNum, csvRow, downloadCsv } from '../../csv'
import { toast } from '../../components/Toast'
import { CardHeading } from '../../components/ui'
import { DocumentHead } from '../../components/DocumentHead'
import { AuswertungsFilter } from './AuswertungsFilter'
import { useStore } from '../../store'
import type { CompetencySetKey, GradingRecord } from '../../types'
import {
  auswertungDruckTeile,
  berichtsKennung,
  briefkopfZulassung,
  formatDelta,
  formatPct,
  MIN_GRADES,
  MIN_SESSIONS,
  REVIEW,
  WATCH,
  type Flag,
  type PeriodKey,
  periodLabel,
  scopeRecords,
  statsBySet,
} from '../../gradingStats'
import { formatDateTime } from '../../datum'
import { useDruckTitel } from '../../useDruckTitel'

/**
 * Standardisierungsbericht nach ORA.ATO.110: Bewertet ein Instruktor
 * systematisch strenger oder milder als der Rest der Flotte? Genau diese
 * Frage muss eine ATO in der Standardisierungsbesprechung beantworten, und
 * genau dafür lag die Grundlage bisher nur roh in der Statistik.
 *
 * Der Bericht ist ein Dokument für die Behörde und deshalb — wie die
 * Formulare — durchgehend englisch, unabhängig von der Bediensprache.
 */

const fmt = (v: number | null, digits = 2) => (v === null ? '–' : v.toFixed(digits))

export function StandardisationReport({
  records,
  setOfRecord,
  fleet,
  onFleetChange,
  fleetOptions,
  authority,
  onAuthorityChange,
  period,
  onPeriodChange,
}: {
  records: GradingRecord[]
  setOfRecord: (r: GradingRecord) => CompetencySetKey | null
  fleet: string
  onFleetChange: (v: string) => void
  fleetOptions: string[]
  authority: '' | 'AT' | 'UK'
  onAuthorityChange: (v: '' | 'AT' | 'UK') => void
  /** Flotte und Zeitraum liegen im Elternteil: Kalibrierungs-Kachel und
   *  Bericht müssen denselben Ausschnitt zeigen, sonst widersprechen sie
   *  einander wieder. */
  period: PeriodKey
  onPeriodChange: (p: PeriodKey) => void
}) {
  // Der Bericht ist ein Behördendokument: Sein gesamter Text kommt aus dem
  // Namensraum `forms`, den es nur auf Englisch gibt (siehe i18n/index.ts).
  const { t } = useTranslation()
  const { state, currentUser } = useStore()

  const doc = state.settings.documentHeader
  // Briefkopf: Zulassung passend zur gewählten Behörde; ohne Auswahl die
  // Hauptzulassung der ATO (AT). Das ist der Absender, nicht der Inhalt —
  // dieselbe Regel wie im Kopf der Statistik (briefkopfZulassung, RPT-01).
  const approval = briefkopfZulassung(authority, doc)
  // Bereichszeile: welche Daten im Bericht stehen. Bei „All authorities"
  // stand hier die AT-Nummer, obwohl UK-Blätter enthalten sein können
  // (Audit 11/2026, GRD-05/STD-01/UID-06). Bildschirm, Druck und CSV
  // nehmen dieselbe Angabe.
  const bereichBehoerde = berichtsKennung(authority, doc)
  const g = state.settings.grading
  const now = Date.now() + state.timeOffsetMs

  const scoped = useMemo(() => scopeRecords(records, { fleet, authority, period, now }), [records, fleet, authority, period, now])

  const sets = useMemo(
    () =>
      statsBySet(scoped, setOfRecord).map((s2) => ({
        ...s2,
        name: g.competencySets.find((c) => c.key === s2.key)?.name ?? s2.key,
        rows: s2.rows.map((r) => ({ ...r, name: state.users.find((u) => u.id === r.id)?.name ?? r.id })),
      })),
    [scoped, setOfRecord, state.users, g.competencySets],
  )

  const label = periodLabel(period)

  // Name des gedruckten PDFs — vorher „Instructor Connect.pdf" für jeden
  // Ausschnitt (Audit 11/2026, EXM-04). Datum auf den Tag, damit der Titel
  // nicht mit jeder Minute neu gesetzt wird.
  useDruckTitel(auswertungDruckTeile(t('forms:std.title'), { fleet, authority, period, doc, now }))

  const exportCsv = () => {
    const row = csvRow
    let csv = row(['Instructor Connect — Standardisation Report'])
    csv += row([doc.atoName, approval])
    csv += row(['Period', label, 'Fleet', fleet || 'All fleets', 'Authority', bereichBehoerde])
    csv += row(['Generated', formatDateTime(now), 'Generated by', currentUser!.name])
    csv += row(['Thresholds', `watch >= ${WATCH.toFixed(2)}`, `review >= ${REVIEW.toFixed(2)}`, `min ${MIN_GRADES} grades / ${MIN_SESSIONS} sessions`])
    csv += row([])
    sets.forEach((s) => {
      csv += row([`Competency set: ${s.name}`])
      csv += row([
        'Instructor', 'Sessions', 'Grades', 'Mean', 'DeviationFromFleetMean',
        'Grade1', 'Grade2', 'Grade3', 'Grade4', 'Grade5', 'NotObserved',
        'ShareGrade1or2Pct', 'ShareGrade4or5Pct', 'NotCompetentRatePct', 'Assessment',
      ])
      s.rows.forEach((r) => {
        csv += row([
          r.name, r.sessions, r.n, csvNum(r.mean), csvNum(r.delta),
          r.dist['1'], r.dist['2'], r.dist['3'], r.dist['4'], r.dist['5'], r.dist.NO,
          csvNum(r.lowShare), csvNum(r.highShare), csvNum(r.ncRate), t(`forms:std.flag.${r.flag}`),
        ])
      })
      csv += row([
        'Fleet mean', s.sessions, s.n, csvNum(s.overall), '',
        '', '', '', '', '', '',
        csvNum(s.lowShare), csvNum(s.highShare), csvNum(s.ncRate), '',
      ])
      csv += row([])
    })
    const d = new Date(now)
    const stamp = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
    toast(t('forms:toast.exported'))
    downloadCsv(`standardisation-report_${stamp}.csv`, csv)
  }

  const flagCls: Record<Flag, string> = {
    none: 'text-dim',
    // „beobachten" mahnt — Ton wait wie in der Statistik; text-warm war im
    // Dunkelmodus ein Off-White und damit kein Status (Audit 11/2026, UID-08)
    watch: 'font-semibold text-wait',
    review: 'font-semibold text-danger',
    insufficient: 'text-dim',
  }

  return (
    <div className="space-y-stack print-landscape">
      {/* Bedienelemente in der Bediensprache — sie stehen nicht auf dem
          Papier. Dieselbe Filterzeile wie in der Statistik (UID-17). */}
      <AuswertungsFilter
        fleet={fleet}
        onFleetChange={onFleetChange}
        fleetOptions={fleetOptions}
        authority={authority}
        onAuthorityChange={onAuthorityChange}
        period={period}
        onPeriodChange={onPeriodChange}
      >
        <button
          onClick={() => window.print()}
          className="min-h-11 flex items-center gap-1.5 rounded-xl border border-line/15 px-3 text-small transition hover:bg-line/5"
        >
          <Printer size={15} /> {t('forms:print')}
        </button>
        <button
          onClick={exportCsv}
          className="min-h-11 flex items-center gap-1.5 rounded-xl border border-line/15 px-3 text-small transition hover:bg-line/5"
          disabled={sets.length === 0}
        >
          <Table2 size={15} /> {t('forms:std.exportCsv')}
        </button>
      </AuswertungsFilter>

      {/* Kopf des Dokuments: ohne ATO, Zeitraum und Flotte ist ein Ausdruck
          nicht zuordenbar — genau daran scheitern Audits. */}
      <DocumentHead
        absender={[doc.atoName, approval]}
        titel={t('forms:std.title')}
        bereich={`${t('forms:std.period.label')}: ${label} · ${t('forms:admin.fleet')}: ${fleet || t('forms:admin.allAircraft')} · ${t('forms:admin.authority')}: ${bereichBehoerde}`}
        stempel={t('forms:exportStamp', { date: formatDateTime(now), name: currentUser!.name })}
      />

      {sets.length === 0 && <p className="pt-4 text-center text-body text-dim">{t('forms:empty')}</p>}

      {sets.map((s) => (
        <div key={s.key} className="rounded-2xl border border-line/10 bg-surface/60 p-3.5">
          <CardHeading className="mb-2">
            {t('forms:std.set')}: <span className="text-ink">{s.name}</span>
          </CardHeading>
          {/* Mindestbreite: Ohne sie schrumpfte die Tabelle bei 1024 px,
              statt zu scrollen, und es stand „Session/s", „Mea/n",
              „Deviatio/n" da (Audit 11/2026, UID-02). */}
          <div className="overflow-x-auto">
            <table className="w-full min-w-[44rem] border-collapse text-micro">
              <thead>
                <tr className="border-b border-line/20 text-left text-dim">
                  <th className="py-1.5 pr-2 font-medium">{t('forms:std.instructor')}</th>
                  <th className="py-1.5 pr-2 text-right font-medium">{t('forms:std.sessionsCol')}</th>
                  <th className="py-1.5 pr-2 text-right font-medium">{t('forms:std.gradesCol')}</th>
                  <th className="py-1.5 pr-2 text-right font-medium">{t('forms:std.meanCol')}</th>
                  <th className="py-1.5 pr-2 text-right font-medium">{t('forms:std.deltaCol')}</th>
                  {['1', '2', '3', '4', '5', 'NO'].map((k) => (
                    <th key={k} className="py-1.5 pr-2 text-right font-medium">
                      {k}
                    </th>
                  ))}
                  {/* „1–2" ist ein Wert: Nach dem Gedankenstrich darf der
                      Browser umbrechen, und es stand „Grade 1–" über „2". */}
                  <th className="whitespace-nowrap py-1.5 pr-2 text-right font-medium">{t('forms:std.lowCol')}</th>
                  <th className="whitespace-nowrap py-1.5 pr-2 text-right font-medium">{t('forms:std.highCol')}</th>
                  <th className="py-1.5 pr-2 text-right font-medium">{t('forms:std.ncCol')}</th>
                  <th className="py-1.5 font-medium">{t('forms:std.assessmentCol')}</th>
                </tr>
              </thead>
              <tbody>
                {s.rows.map((r) => (
                  <tr key={r.id} className="border-b border-line/10">
                    <td className="break-normal py-1.5 pr-2 font-medium">{r.name}</td>
                    <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{r.sessions}</td>
                    <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{r.n}</td>
                    <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{fmt(r.mean)}</td>
                    <td className={`whitespace-nowrap py-1.5 pr-2 text-right tabular-nums ${flagCls[r.flag]}`}>{formatDelta(r.delta)}</td>
                    {['1', '2', '3', '4', '5', 'NO'].map((k) => (
                      <td key={k} className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums text-dim">
                        {r.dist[k] || '–'}
                      </td>
                    ))}
                    <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{formatPct(r.lowShare)}</td>
                    <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{formatPct(r.highShare)}</td>
                    <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{formatPct(r.ncRate)}</td>
                    <td className={`break-normal py-1.5 ${flagCls[r.flag]}`}>{t(`forms:std.flag.${r.flag}`)}</td>
                  </tr>
                ))}
                <tr className="border-t-2 border-line/30 font-semibold">
                  <td className="break-normal py-1.5 pr-2">{t('forms:std.fleetMean')}</td>
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{s.sessions}</td>
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{s.n}</td>
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{fmt(s.overall)}</td>
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">—</td>
                  {['1', '2', '3', '4', '5', 'NO'].map((k) => (
                    <td key={k} className="py-1.5 pr-2" />
                  ))}
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{formatPct(s.lowShare)}</td>
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{formatPct(s.highShare)}</td>
                  <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums">{formatPct(s.ncRate)}</td>
                  <td />
                </tr>
              </tbody>
            </table>
          </div>
        </div>
      ))}

      {sets.length > 0 && (
        <p className="text-micro leading-relaxed text-dim">
          {t('forms:std.footnote', { watch: WATCH.toFixed(2), review: REVIEW.toFixed(2), grades: MIN_GRADES, sessions: MIN_SESSIONS })}
        </p>
      )}
    </div>
  )
}
